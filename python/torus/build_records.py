"""Assemble data/torus/records.json from raw search results, certifying every entry.

  python3 python/torus/build_records.py --raw data/torus/raw --out data/torus

For each (family, N, P) the candidates are: the raw result; for free, the sq and
hex results read as free-lattice packings; for every family, the P+1 result with
its last piece removed (L(P) <= L(P+1) because deleting a piece keeps a packing
valid). The best candidate is certified with the smallest shrink eps on a ladder
that the interval certifier (certify_torus.py) accepts; score_cert is the
smallest double >= the certified upper bound of score/(1 - eps). Standard
library only (plus the certifier's mpmath).

  python3 python/torus/build_records.py --refresh data/torus/records.json --out data/torus

re-derives the bound, literature, closed form, notes and status of every record from
literature_torus.py and leaves configurations, scores and certificates as they are. A record is
proven only through a literature entry that certify_torus.proof_entry accepts.
"""

import argparse
import datetime
import json
import math
import os
import sys
from decimal import ROUND_HALF_EVEN, Decimal

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import certify_torus as C  # noqa: E402
import literature_torus as LIT  # noqa: E402

DISPLAY_RULE = "score_cert rounded to the nearest at 6 decimals (exact binary64 value, ties to even)"
CONVENTIONS = {
    "problem_id": "torus/<family>/<N>/<P>",
    "pieces": "N = 0: disk of diameter 1 (radius 1/2); N >= 3: regular N-gon of side 1, vertex k at (x, y) + R (cos a_k, sin a_k), a_k = theta + pi/2 + 2 pi k/N, R = 1/(2 sin(pi/N)); theta in radians",
    "families": {
        "sq": "lattice L Z^2; lattice = {L}; score L",
        "hex": "lattice generated by L (1, 0) and L (1/2, sqrt(3)/2); lattice = {L}; score L",
        "free": "any lattice; lattice = {b1, b2}; score sqrt(|det(b1, b2)|) = sqrt(cell area)",
    },
    "validity": "interiors of all pieces and all their lattice translates pairwise disjoint, including a piece and its own nonzero translates",
    "score_float": "score of the stored configuration (search result, float)",
    "score_cert": "proven: shrinking every piece of the stored configuration by (1 - eps) about its centre leaves all image pairs strictly separated (mpmath interval certificate); scaling the plane by score_cert/score_float >= 1/(1 - eps) then gives a valid packing of full-size pieces at score_cert",
    "display": DISPLAY_RULE,
    "density": "P * piece area / cell area of the stored configuration",
    "units": "polygon side 1, disk diameter 1",
}


EPS_LADDER = (1e-12, 1e-11, 1e-10, 1e-9)
# Proven clearances below this are valid but too thin for a float re-check (the TypeScript
# records test re-validates the shrunk configuration in doubles); take the next eps instead.
MIN_CLEARANCE = 5e-14
SOFTWARE = "PolyPack torus research build"
FOUND_BY = "PolyPack research"
SQ3_2 = math.sqrt(3.0) / 2.0


def piece_area(N):
    return math.pi / 4.0 if N == 0 else N / (4.0 * math.tan(math.pi / N))


def basis_of(rec):
    fam = rec["family"]
    p = rec["params"]
    if fam == "sq":
        return (p[0], 0.0), (0.0, p[0])
    if fam == "hex":
        return (p[0], 0.0), (0.5 * p[0], SQ3_2 * p[0])
    return (p[0], 0.0), (p[1], p[2])


def score_float(fam, b1, b2, L=None):
    if fam in ("sq", "hex"):
        return L
    return math.sqrt(abs(b1[0] * b2[1] - b1[1] * b2[0]))


def norm_theta(N, th):
    if N == 0:
        return 0.0
    per = 2 * math.pi / N
    return th - per * math.floor(th / per)


# The search tools (torus_search.py, torus_np.py, polish_raw.py, extend_torus.py) work in radius-1
# units for disks and write raw results tagged "units": "working" (older files have no tag). The
# records are in site units (disk diameter 1), so a disk result is converted here, at the one
# edge: lengths times 1/2, exact in binary64. Polygons, and raw tagged "diameter", are unchanged.
DISK_SITE_PER_WORKING = 0.5


def raw_length_factor(N, raw):
    return 1.0 if N != 0 or raw.get("units") == "diameter" else DISK_SITE_PER_WORKING


def candidate(fam, N, P, raw, label):
    """A certifier input from a raw search result (possibly of another family), in site units."""
    f = raw_length_factor(N, raw)
    b1, b2 = basis_of(raw)
    b1, b2 = (b1[0] * f, b1[1] * f), (b2[0] * f, b2[1] * f)
    poses = [[float(x) * f, float(y) * f, norm_theta(N, float(t))] for x, y, t in raw["poses"]]
    if fam in ("sq", "hex"):
        lattice = {"L": float(raw["params"][0]) * f}
        sf = float(raw["params"][0]) * f
    else:
        lattice = {"b1": [float(b1[0]), float(b1[1])], "b2": [float(b2[0]), float(b2[1])]}
        sf = score_float("free", b1, b2)
    return {
        "family": fam,
        "N": N,
        "P": P,
        "lattice": lattice,
        "poses": poses,
        "score_float": sf,
        "label": label,
        "raw": raw,
    }


def drop_last(cand):
    c = dict(cand)
    c["P"] = cand["P"] - 1
    c["poses"] = cand["poses"][:-1]
    c["label"] = "P+1 result minus one piece (" + cand["label"] + ")"
    return c


def certify_candidate(c):
    last = None
    for eps in EPS_LADDER:
        rec = {k: c[k] for k in ("family", "N", "P", "lattice", "poses")}
        rec["eps"] = eps
        try:
            cert = C.certify(rec)
        except C.CertError as e:
            last = str(e)
            continue
        if float(cert["min_clearance_lb"]) < MIN_CLEARANCE:
            last = "clearance %s below %g" % (cert["min_clearance_lb"], MIN_CLEARANCE)
            continue
        rec["score_cert"] = cert["score_upper_float"]
        cert = C.certify(rec)  # re-check with the claim
        return eps, cert
    raise C.CertError("no eps on the ladder certifies: %s" % last)


def annotate(fam, N, P, sf, sc, label):
    """Bound, closed form, literature, notes and status of a record (from literature_torus.py)."""
    bound = LIT.score_bound(fam, N, P)
    lit = LIT.literature(fam, N, P)
    notes = []
    gap_rel = (sf - bound["value"]) / bound["value"]
    exact = LIT.exact_form(fam, N, P, sf)
    if gap_rel <= 1e-12:
        notes.append("[CALC] score_float equals the lower bound (%s) to 1e-12 relative." % bound["label"])
        if exact:
            notes.append(
                "[CALC] Exact value %s = %.15g (a lattice, double-lattice or tiling construction attains the bound); the stored floats certify score_cert just above it."
                % (exact["expr"], exact["value"])
            )
    if label.startswith("P+1") or "as a free lattice" in label:
        notes.append("Taken from: %s." % label)
    for L_ in lit:
        if L_.get("value") is not None:
            d = sf - L_["value"]
            notes.append("Literature %s value %.10f (%s): ours - literature = %.3e." % (L_["status"], L_["value"], L_["short"], d))
    proof = C.proof_entry(lit, sc)
    if proof is not None:
        notes.append("Proven optimal: %s (%s; doi:%s)." % (proof["short"], proof["proof"], proof["doi"]))
    return {
        "status": "proven" if proof is not None else "best_known",
        "bound": bound,
        "exact": exact if gap_rel <= 1e-12 else None,
        "literature": lit,
        "notes": " ".join(notes),
        "gap_rel": gap_rel,
    }


def refresh(path, out_dir):
    """Re-derive every record's metadata from literature_torus.py; the packings stay as they are."""
    with open(path) as f:
        data = json.load(f)
    if data.get("units") != "diameter":
        raise SystemExit(
            "%s is not in site units (header units != \"diameter\"): convert it first (scripts/convert-units.ts)" % path
        )
    changed = []
    for r in data["records"]:
        meta = annotate(r["family"], r["N"], r["P"], r["score_float"], r["score_cert"], r.get("search_label") or "")
        meta.pop("gap_rel")
        before = {k: r.get(k) for k in meta}
        r.update(meta)
        C.check_status(r)
        if before != meta:
            changed.append((r["problem"], sorted(k for k in meta if before[k] != meta[k]), before["status"], meta["status"]))
    with open(os.path.join(out_dir, "records.json"), "w") as f:
        json.dump(data, f, indent=1)
    for pid, keys, s0, s1 in changed:
        print("REFRESHED %-18s %s%s" % (pid, ", ".join(keys), "" if s0 == s1 else "  (status %s -> %s)" % (s0, s1)))
    print("refreshed %d of %d records; %d proven" % (len(changed), len(data["records"]), sum(r["status"] == "proven" for r in data["records"])))


def display(x, digits=6):
    """score_cert rounded to the nearest at 6 decimals, from its exact binary64 value
    (ties to even); always 6 decimals, e.g. 2.000000000002 -> "2.000000"."""
    q = Decimal(1).scaleb(-digits)
    return str(Decimal(x).quantize(q, rounding=ROUND_HALF_EVEN))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default=None, help="raw search results (required unless --refresh)")
    ap.add_argument("--out", required=True)
    ap.add_argument(
        "--refresh",
        default=None,
        help="existing records.json: re-derive bound, literature, closed form, notes and status of every "
        "record from literature_torus.py; configurations, scores and certificates are kept",
    )
    ap.add_argument("--Ns", default="0,3,4,5,6,7,8")
    ap.add_argument("--Pmax", type=int, default=16, help="searched range 1..Pmax")
    ap.add_argument("--raw-ext", default=None, help="extension results (extend_torus.py) for P > Pmax")
    ap.add_argument("--Pext", type=int, default=49)
    ap.add_argument(
        "--only-improve",
        default=None,
        help="existing records.json: keep every record (byte-identical apart from the display "
        "rule) unless the best candidate is lower by more than --min-gain relative; certify and "
        "replace only those",
    )
    ap.add_argument("--min-gain", type=float, default=1e-11, help="relative gain needed to replace a record")
    args = ap.parse_args()
    if args.refresh:
        refresh(args.refresh, args.out)
        return
    if not args.raw:
        ap.error("--raw is required unless --refresh is given")
    existing = None
    if args.only_improve:
        with open(args.only_improve) as f:
            existing_file = json.load(f)
        if existing_file.get("units") != "diameter":
            ap.error("--only-improve file is not in site units (header units != \"diameter\"): convert it first")
        existing = {r["problem"]: r for r in existing_file["records"]}
    changed = []
    display_changes = []
    Ns = [int(v) for v in args.Ns.split(",")]
    certdir = os.path.join(args.out, "certificates")
    os.makedirs(certdir, exist_ok=True)

    def load_from(d, fam, N, P):
        if d is None:
            return None
        fn = os.path.join(d, "%s_%d_%d.json" % (fam, N, P))
        if not os.path.exists(fn):
            return None
        with open(fn) as f:
            return json.load(f)

    def loads(fam, N, P):
        """Search result (P <= Pmax) and exact replication (any P), when present."""
        out = []
        if P <= args.Pmax:
            out.append(load_from(args.raw, fam, N, P))
        out.append(load_from(args.raw_ext, fam, N, P))
        return [r for r in out if r is not None]

    Ptop = args.Pext if args.raw_ext else args.Pmax

    records = []
    report = []
    for fam in ("sq", "hex", "free"):
        for N in Ns:
            chosen = {}
            for P in range(Ptop, 0, -1):
                cands = []
                for raw in loads(fam, N, P):
                    cands.append(candidate(fam, N, P, raw, raw.get("label", "search")))
                if fam == "free":
                    for fam2 in ("sq", "hex"):
                        for r2 in loads(fam2, N, P):
                            cands.append(candidate("free", N, P, r2, "%s result as a free lattice" % fam2))
                if (P + 1) in chosen and P < args.Pmax:
                    cands.append(drop_last(chosen[P + 1]))
                if not cands:
                    continue
                cands.sort(key=lambda c: c["score_float"])
                chosen[P] = cands[0]
            for P in range(1, Ptop + 1):
                if P not in chosen:
                    continue
                c = chosen[P]
                pid = "torus/%s/%d/%d" % (fam, N, P)
                if existing is not None and pid in existing:
                    old_rec = existing[pid]
                    new_display = display(old_rec["score_cert"])
                    if old_rec["display"] != new_display:
                        display_changes.append((pid, old_rec["display"], new_display))
                        old_rec["display"] = new_display
                    if not c["score_float"] < old_rec["score_float"] * (1 - args.min_gain):
                        records.append(old_rec)
                        continue
                    try:
                        eps, cert = certify_candidate(c)
                    except C.CertError as e:
                        print("%s: candidate %.12f not certified (%s); kept" % (pid, c["score_float"], e))
                        records.append(old_rec)
                        continue
                    if not cert["score_upper_float"] < old_rec["score_cert"]:
                        records.append(old_rec)
                        continue
                    changed.append((pid, old_rec["score_float"], old_rec["score_cert"], c["score_float"], cert["score_upper_float"], c["label"]))
                else:
                    eps, cert = certify_candidate(c)
                certname = "certificates/%s_%d_%d.json" % (fam, N, P)
                with open(os.path.join(args.out, certname), "w") as f:
                    json.dump(cert, f, indent=1)
                b1, b2 = (c["lattice"]["b1"], c["lattice"]["b2"]) if fam == "free" else basis_of(
                    {"family": fam, "params": [c["lattice"]["L"]]}
                )
                area = abs(b1[0] * b2[1] - b1[1] * b2[0])
                dens = P * piece_area(N) / area
                sc = cert["score_upper_float"]
                meta = annotate(fam, N, P, c["score_float"], sc, c["label"])
                bound, gap_rel = meta["bound"], meta["gap_rel"]
                raw = c["raw"]
                rec = {
                    "problem": pid,
                    "family": fam,
                    "N": N,
                    "P": P,
                    "score_float": c["score_float"],
                    "score_cert": sc,
                    "display": display(sc),
                    "status": meta["status"],
                    "density": dens,
                    "eps": eps,
                    "configuration": {"lattice": c["lattice"], "poses": c["poses"]},
                    "certificate": certname,
                    "min_clearance_shrunk": cert["min_clearance_lb"],
                    "bound": bound,
                    "exact": meta["exact"],
                    "literature": meta["literature"],
                    "method": raw.get("method", "search"),
                    "seed": raw.get("seed"),
                    "budget": raw.get("budget"),
                    "search_label": c["label"],
                    "software": SOFTWARE,
                    "found_by": FOUND_BY,
                    "notes": meta["notes"],
                }
                C.check_status(rec)
                records.append(rec)
                report.append(
                    "%-18s %.10f cert %.10f eps %.0e dens %.6f bound %.10f gap %.2e %s"
                    % (pid, c["score_float"], sc, eps, dens, bound["value"], gap_rel, c["label"][:30])
                )
                print(report[-1], flush=True)
    if existing is not None:
        # same order as the existing file; untouched records are the same objects
        order = {r["problem"]: k for k, r in enumerate(existing_file["records"])}
        records.sort(key=lambda r: order.get(r["problem"], len(order)))
        for pid, sf0, sc0, sf1, sc1, label in changed:
            print("CHANGED %s score_float %.12f -> %.12f, score_cert %.12f -> %.12f (%s)" % (pid, sf0, sf1, sc0, sc1, label))
        print("changed %d records" % len(changed))
        print("display strings changed in kept records: %d" % len(display_changes))
        existing_file["conventions"]["display"] = DISPLAY_RULE
    out = {
        "generated": datetime.date.today().isoformat() if existing is None else existing_file["generated"],
        "units": "diameter",
        "conventions": existing_file["conventions"] if existing is not None else CONVENTIONS,
        "records": records,
    }
    with open(os.path.join(args.out, "records.json"), "w") as f:
        json.dump(out, f, indent=1)
    print("wrote %d records" % len(records))


if __name__ == "__main__":
    main()
