def snap(v, dps):
    mp.mp.dps = dps
    cands = {0: mp.mpf(0), 1: mp.mpf(1), -1: mp.mpf(-1), 'h': mp.mpf(1) / 2, 'mh': -mp.mpf(1) / 2,
             's2': mp.sqrt(2) / 2, 'ms2': -mp.sqrt(2) / 2, 's3': mp.sqrt(3) / 2, 'ms3': -mp.sqrt(3) / 2}
    k = min(cands, key=lambda c: abs(float(cands[c]) - v))
    assert abs(float(cands[k]) - v) < 1e-9, v
    return cands[k]


def refine(X, gens, edges, dps):
    mp.mp.dps = dps
    V = len(X)
    Gm = [mp.matrix([[snap(float(g[i, j]), dps) for j in range(3)] for i in range(3)]) for g in gens]
    perms = []
    for g in gens:
        perm = []
        for i in range(V):
            q = g @ X[i]
            d = np.linalg.norm(X - q, axis=1)
            k = int(np.argmin(d)); assert d[k] < 1e-6
            perm.append(k)
        perms.append(perm)
    x = mp.matrix([mp.mpf(float(c)) for p in X for c in p])
    def resid(x):
        r = []
        for a, b, tg in edges:
            r.append(mp.sqrt(sum((x[3 * a + i] - x[3 * b + i]) ** 2 for i in range(3))) - tg)
        for g, perm in zip(Gm, perms):
            for i in range(V):
                for c in range(3):
                    r.append(x[3 * perm[i] + c] - sum(g[c, k] * x[3 * i + k] for k in range(3)))
        for c in range(3): r.append(sum(x[3 * i + c] for i in range(V)))
        return r
    def jac(x):
        n = len(x)
        rows = []
        for a, b, tg in edges:
            d = mp.sqrt(sum((x[3 * a + i] - x[3 * b + i]) ** 2 for i in range(3)))
            row = {}
            for i in range(3):
                t = (x[3 * a + i] - x[3 * b + i]) / d
                row[3 * a + i] = t; row[3 * b + i] = -t
            rows.append(row)
        for g, perm in zip(Gm, perms):
            for i in range(V):
                for c in range(3):
                    row = {3 * perm[i] + c: mp.mpf(1)}
                    for k in range(3): row[3 * i + k] = row.get(3 * i + k, 0) - g[c, k]
                    rows.append(row)
        for c in range(3): rows.append({3 * i + c: mp.mpf(1) for i in range(V)})
        return rows
    for it in range(40):
        r = resid(x)
        nr = max(abs(v) for v in r)
        if nr < mp.mpf(10) ** (-(dps - 25)): break
        rows = jac(x); n = len(x)
        M = mp.zeros(n, n); rhs = mp.zeros(n, 1)
        for row, rv in zip(rows, r):
            for i, vi in row.items():
                rhs[i] -= vi * rv
                for k, vk in row.items(): M[i, k] += vi * vk
        for i in range(n): M[i, i] += mp.mpf(10) ** -(dps // 2)
        x = x + mp.lu_solve(M, rhs)
    print(f'  refined: residual {mp.nstr(nr, 3)} after {it} iterations')
    return x


def find_minpoly(vals, maxdeg=48, dps=400, log=print):
    """Minimal polynomial of a primitive element of the field generated by vals (mpf list)."""
    mp.mp.dps = dps
    rnd = random.Random(1)
    # build alpha incrementally to keep it small: alpha = sum of coordinates with small integer weights
    uniq = []
    for v in vals:
        if abs(v) < mp.mpf(10) ** -50: continue
        if all(abs(abs(v) - abs(u)) > mp.mpf(10) ** -50 for u in uniq): uniq.append(v)
    for attempt in range(20):
        w = [rnd.randint(1, 3) for _ in uniq] if attempt else [1] * len(uniq)
        alpha = sum(wi * v for wi, v in zip(w, uniq))
        for deg in (2, 3, 4, 6, 8, 12, 16, 24, 32, 48):
            if deg > maxdeg: break
            mc = 10 ** 18
            p = mp.findpoly(alpha, deg, maxcoeff=mc, maxsteps=100000, tol=mp.mpf(10) ** -(dps - 60))
            if p:
                return w, uniq, alpha, [int(c) for c in p][::-1], deg
        log(f'   attempt {attempt} failed')
    return None
