/**
 * Regenerates the boundary search results used by the records (data/boundary/sources/
 * search_2026-10-25.json): each is one deterministic call
 *   searchBoundary({ polytope: "tesseract", piece, P }, { seed: 1, budget: { evals: E } })
 * with no time limit, so the same call returns the same configuration. Runs are made one after
 * another; existing entries of the output file are kept unless re-run.
 *
 * Usage: npx tsx packages/boundary/scripts/search-sources.ts [--only ball/5 cube/11 ...] [--out file]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { BoundaryConfig, PieceName } from "../src/index";
import { searchBoundary, validateBoundary } from "../src/index";

const DATE = "2026-10-25";
const SEED = 1;
/** problem, evaluation budget, and the value the run is expected to reproduce (as first reported). */
const RUNS: [PieceName, number, number, number][] = [
  ["ball", 5, 2617672, 1.7872262714],
  ["ball", 8, 65479, 1.9318516527],
  ["ball", 10, 654968, 2.26926726],
  ["ball", 11, 1358135, 2.3159183399],
  ["ball", 13, 7650384, 2.3974954214],
  ["ball", 15, 5026907, 2.503239533],
  ["ball", 16, 779083, 2.5265737257],
  ["cube", 11, 156372, 1.25],
  ["cube", 12, 490433, 1.25],
  ["cube", 13, 298374, 4 / 3],
  ["cube", 14, 2007977, 4 / 3],
];

const args = process.argv.slice(2);
const outAt = args.indexOf("--out");
const out =
  outAt >= 0
    ? args[outAt + 1]
    : fileURLToPath(new URL(`../../../data/boundary/sources/search_${DATE}.json`, import.meta.url));
const onlyAt = args.indexOf("--only");
const only = onlyAt >= 0 ? args.slice(onlyAt + 1).filter((a) => !a.startsWith("--")) : null;

interface Entry {
  piece: PieceName;
  P: number;
  method: string;
  call: string;
  seed: number;
  evals_budget: number;
  evals_used: number;
  ended: string;
  starts: number;
  date: string;
  value: number;
  config: BoundaryConfig;
  wall_s: number;
}
const file: { note: string; runs: Record<string, Entry> } = existsSync(out)
  ? JSON.parse(readFileSync(out, "utf8"))
  : { note: "", runs: {} };
file.note =
  "PolyPack boundary search (packages/boundary/src/search): one deterministic call per problem, searchBoundary({polytope: 'tesseract', piece, P}, {seed, budget: {evals}}), no time limit; regenerated by packages/boundary/scripts/search-sources.ts. value = the returned s (valid at tol 0 by the engine); wall_s is the run's time on the machine that made it, for information.";

let failed = 0;
for (const [piece, P, E, expect] of RUNS) {
  const key = `${piece}/${P}`;
  if (only && !only.includes(key)) continue;
  const t0 = performance.now();
  const r = searchBoundary({ polytope: "tesseract", piece, P }, { seed: SEED, budget: { evals: E } });
  const wall = (performance.now() - t0) / 1000;
  if (!r.config || r.score === null) {
    console.log(`FAIL ${key}: no configuration`);
    failed++;
    continue;
  }
  const ok = validateBoundary({ polytope: "tesseract", piece, P }, r.config, { tol: 0 }).ok;
  const match = Math.abs(r.score - expect) <= 1e-9 * expect;
  file.runs[key] = {
    piece,
    P,
    method: "PolyPack boundary search",
    call: `searchBoundary({polytope: "tesseract", piece: "${piece}", P: ${P}}, {seed: ${SEED}, budget: {evals: ${E}}})`,
    seed: SEED,
    evals_budget: E,
    evals_used: r.evals,
    ended: r.ended,
    starts: r.starts,
    date: DATE,
    value: r.score,
    config: r.config,
    wall_s: Math.round(wall * 10) / 10,
  };
  if (!ok || !match) failed++;
  console.log(
    `${ok && match ? "OK  " : "FAIL"} ${key}: s = ${r.score} (expected ${expect}${match ? "" : ", DIFFERS"}), valid at tol 0: ${ok}, ${r.evals} evals, ${r.ended}, ${r.starts} starts, ${wall.toFixed(1)} s`,
  );
  // written after every run, so a long batch keeps what it has; entries in the order of RUNS
  const ordered: Record<string, Entry> = {};
  for (const [pc, n] of RUNS) if (file.runs[`${pc}/${n}`]) ordered[`${pc}/${n}`] = file.runs[`${pc}/${n}`];
  file.runs = ordered;
  writeFileSync(out, JSON.stringify(file, null, 1) + "\n");
}
process.exit(failed ? 1 : 0);
