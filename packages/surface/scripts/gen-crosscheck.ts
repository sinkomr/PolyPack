/**
 * Random configurations with the TypeScript validator's verdict, for the Python certifier's
 * cross-check test (python/surface/test_cert.py). Only configurations whose verdict holds with a
 * clear margin (>= 1e-6) are kept, so both sides must agree on every one.
 *
 * Usage: npx tsx packages/surface/scripts/gen-crosscheck.ts <out.json>            (Platonic solids)
 *        npx tsx packages/surface/scripts/gen-crosscheck.ts --general <out.json>  (the Archimedean and Catalan solids, prisms, antiprisms)
 *        npx tsx packages/surface/scripts/gen-crosscheck.ts --johnson <out.json>  (the 92 Johnson solids)
 */
import { writeFileSync } from "node:fs";
import { ALL_SOLID_NAMES, JOHNSON_NAMES, SOLID_NAMES, type SolidName, faceVertex, getSolid, validateFold, validateNofold } from "../src/index";
import { mulberry32, randomPose } from "../src/search/search";

const johnson = process.argv[2] === "--johnson";
const general = process.argv[2] === "--general" || johnson;
const out = process.argv[general ? 3 : 2];
const NEW = johnson
  ? [...JOHNSON_NAMES]
  : ALL_SOLID_NAMES.filter((n) => !(SOLID_NAMES as readonly string[]).includes(n) && !(JOHNSON_NAMES as readonly string[]).includes(n));

/** Mean edge length at scale 1, so that pieces and faces have comparable sizes on every solid. */
function meanEdge(name: SolidName): number {
  const S = getSolid(name);
  let total = 0;
  for (let f = 0; f < S.F; f++)
    for (let k = 0; k < S.sides[f]; k++) {
      const [ax, ay] = faceVertex(S, 1, f, k);
      const [bx, by] = faceVertex(S, 1, f, k + 1);
      total += Math.hypot(bx - ax, by - ay);
    }
  return total / (2 * S.E);
}

const rand = mulberry32(johnson ? 2028 : general ? 2027 : 2026);
const cases: any[] = [];
const want = { valid: 0, invalid: 0 };
const target = johnson ? 150 : general ? 80 : 120;
for (let t = 0; t < 200000 && cases.length < 2 * target; t++) {
  const solid = general ? NEW[t % NEW.length] : SOLID_NAMES[t % 5];
  const S = getSolid(solid);
  const N = [0, 3, 4, 5, 6, 8][Math.floor(rand() * 6)];
  const P = 1 + Math.floor(rand() * 3);
  const mode = rand() < 0.75 ? "fold" : "nofold";
  const s = ((mode === "fold" ? 1.2 : 2.2) + 2.5 * rand()) / (general ? meanEdge(solid) : 1);
  const pieces = Array.from({ length: P }, () => {
    const p = randomPose(S, rand);
    return { face: p.face, x: p.x * s, y: p.y * s, theta: p.theta };
  });
  const cfg = { solid, N, s, pieces };
  const v = mode === "fold" ? validateFold(cfg, { tol: 0 }) : validateNofold(cfg, { tol: 0 });
  const margins = [v.minPairSep, v.minConeSep, v.minWallSep].filter((m) => Number.isFinite(m));
  const worst = margins.length ? Math.min(...margins) : Infinity;
  const valid = v.ok;
  if (Math.abs(worst) < 1e-6) continue;
  // keep the two classes balanced
  if (valid && want.valid >= target) continue;
  if (!valid && want.invalid >= target) continue;
  want[valid ? "valid" : "invalid"]++;
  cases.push({ id: `cross/${t}`, solid, mode, N, P, s, pieces, ts_valid: valid, ts_margin: worst, ts_errors: v.errors.slice(0, 2) });
}
const note = johnson
  ? "generated by packages/surface/scripts/gen-crosscheck.ts --johnson (seed 2028)"
  : general
  ? "generated by packages/surface/scripts/gen-crosscheck.ts --general (seed 2027)"
  : "generated by packages/surface/scripts/gen-crosscheck.ts (seed 2026)";
writeFileSync(out, JSON.stringify({ note, cases }));
console.log("wrote", cases.length, want);
