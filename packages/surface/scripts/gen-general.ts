/**
 * Writes packages/surface/src/general.data.ts: the vertices and faces of the solids beyond the five
 * Platonic ones (the 13 Archimedean and 13 Catalan solids, the prisms with 3 and 5 to 12 sides and the antiprisms with 4
 * to 12 sides), copied from the polyhedra space's solids (packages/polyhedra/src/solids.data.ts,
 * generated from python/polyhedra/solids_exact.json: each coordinate is the nearest binary64 of its
 * exact value). Only the coordinates, faces, family and title are kept; packages/surface derives
 * everything else. The certifier reads solids_exact.json itself.
 *
 * Usage: npx tsx packages/surface/scripts/gen-general.ts
 */
import { writeFileSync } from "node:fs";
import { SOLID_DATA } from "../../polyhedra/src/solids.data";

const ARCHIMEDEAN = SOLID_DATA.filter((d) => d.family === "archimedean").map((d) => d.name);
const CATALAN = SOLID_DATA.filter((d) => d.family === "catalan").map((d) => d.name);
const PRISMS = [3, 5, 6, 7, 8, 9, 10, 11, 12].map((n) => `prism${n}`);
const ANTIPRISMS = [4, 5, 6, 7, 8, 9, 10, 11, 12].map((n) => `antiprism${n}`);
const names = [...ARCHIMEDEAN, ...CATALAN, ...PRISMS, ...ANTIPRISMS];

const lines: string[] = [];
lines.push("// Generated by packages/surface/scripts/gen-general.ts from packages/polyhedra/src/solids.data.ts");
lines.push("// (the nearest binary64 of the exact coordinates of python/polyhedra/solids_exact.json). Do not edit by hand.");
lines.push("");
lines.push("export interface GeneralSolidData {");
lines.push("  name: string;");
lines.push('  family: "archimedean" | "catalan" | "prism" | "antiprism";');
lines.push("  title: string;");
lines.push("  /** vertices of the canonical solid, centred at the origin */");
lines.push("  V: [number, number, number][];");
lines.push("  /** faces as vertex cycles, counter-clockwise seen from outside */");
lines.push("  faces: number[][];");
lines.push("}");
lines.push("");
lines.push("export const GENERAL_SOLID_DATA: GeneralSolidData[] = [");
for (const name of names) {
  const d = SOLID_DATA.find((x) => x.name === name);
  if (!d) throw new Error(`no solid ${name}`);
  lines.push("  {");
  lines.push(`    name: ${JSON.stringify(d.name)}, family: ${JSON.stringify(d.family)}, title: ${JSON.stringify(d.title)},`);
  lines.push(`    V: ${JSON.stringify(d.V)},`);
  lines.push(`    faces: ${JSON.stringify(d.faces)},`);
  lines.push("  },");
}
lines.push("];");
const path = new URL("../src/general.data.ts", import.meta.url);
writeFileSync(path, lines.join("\n") + "\n");
console.log("wrote", names.length, "solids to", path.pathname);
