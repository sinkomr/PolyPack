/**
 * Test packings (not records) on Johnson solids, for N = 0 (disks), 3 and 4, folding and not, certified exactly by
 * python/surface/test_general.py and validated by packages/surface/test/johnson.test.ts. Two kinds:
 *  - constructed, without search: a nofold packing with one piece on a face of every kind and two on the smallest
 *    kind, and a fold packing of two pieces facing each other across an edge between faces of different kinds
 *    (any edge when the solid has one kind of face);
 *  - found by a short seeded search of the surface package (P = 3, one start, one hop, the first of 24 seeds that ends
 *    valid): not good packings, only valid ones.
 * Usage: npx tsx packages/surface/scripts/build-johnson-packings.ts
 */
import { writeFileSync } from "node:fs";
import { pieceReach } from "../src/disk";
import { apply, faceVertex, getSolid, glue, inverse, sizeFor, validate, type SolidName, type SurfacePose } from "../src/index";
import { searchProblem } from "../src/search/search";

// J1, J3, J6, J12, J37, J44, J72, J84, J86, J90, J92
const SOLIDS: SolidName[] = [
  "square_pyramid",
  "triangular_cupola",
  "pentagonal_rotunda",
  "triangular_bipyramid",
  "elongated_square_gyrobicupola",
  "gyroelongated_triangular_bicupola",
  "gyrate_rhombicosidodecahedron",
  "snub_disphenoid",
  "sphenocorona",
  "disphenocingulum",
  "triangular_hebesphenorotunda",
];
const packings: unknown[] = [];
for (const solid of SOLIDS) {
  const S = getSolid(solid);
  const kinds = [...new Set(S.sides)].sort((a, b) => a - b);
  for (const N of [0, 3, 4]) {
    const R = pieceReach(N);
    const s = 16 * R;
    for (const mode of ["fold", "nofold"] as const) {
      let pieces: SurfacePose[];
      if (mode === "nofold") {
        pieces = kinds.map((m) => ({ face: S.sides.indexOf(m), x: 0, y: 0, theta: 0.173 }));
        pieces[0].x = -1.2 * R;
        pieces.push({ ...pieces[0], x: 1.2 * R, theta: 0.317 });
      } else {
        let f = S.faces.findIndex((_, fi) => S.adj[fi].some((g) => S.sides[g.face] !== S.sides[fi]));
        if (f < 0) f = 0;
        const k = Math.max(0, S.adj[f].findIndex((g) => S.sides[g.face] !== S.sides[f]));
        const a = faceVertex(S, s, f, k);
        const b = faceVertex(S, s, f, k + 1);
        const dx = b[0] - a[0], dy = b[1] - a[1];
        const L = Math.hypot(dx, dy);
        const nx = -dy / L, ny = dx / L;
        const d = 0.15 * R;
        const g = glue(S, s, f, k);
        const p = { face: f, x: a[0] + 0.31 * dx + d * nx, y: a[1] + 0.31 * dy + d * ny, theta: 0.173 };
        const q = apply(inverse(g.T), a[0] + 0.69 * dx - d * nx, a[1] + 0.69 * dy - d * ny);
        pieces = [p, { face: g.face, x: q[0], y: q[1], theta: 0.317 }];
      }
      const rec = { id: `surface/${solid}/${mode}/${N}/${pieces.length}`, solid, mode, N, P: pieces.length, s, pieces, how: "constructed" };
      const v = validate(rec, mode, { tol: 0 });
      if (!v.ok) throw new Error(`${rec.id}: ${v.errors.join(", ")}`);
      if (mode === "fold" && validate(rec, "nofold").ok) throw new Error(`${rec.id}: no crossing`);
      packings.push(rec);
    }
    // a short search: valid, not good
    for (const mode of ["fold", "nofold"] as const) {
      const t = Date.now();
      // the legacy search starts at a scale from the area, which a high-area solid without folding cannot meet from one
      // start (it needs a piece to fit a face); take the first of a few seeds that ends valid
      let seed = 1;
      let r = searchProblem(S, N, 3, { seed, randomStarts: 1, hops: 1, warm: [], mode });
      while (!r && seed < 24) r = searchProblem(S, N, 3, { seed: ++seed, randomStarts: 1, hops: 1, warm: [], mode });
      if (!r) {
        console.log(`surface/${solid}/${mode}/${N}/3: no valid search result in 24 seeds (skipped)`);
        continue;
      }
      const sc = sizeFor(N, r.lam);
      const pcs = r.poses.map((p) => ({ face: p.face, x: p.x * sc, y: p.y * sc, theta: p.theta }));
      const rec = { id: `surface/${solid}/${mode}/${N}/3`, solid, mode, N, P: 3, s: sc, pieces: pcs, how: `search seed ${seed}` };
      const v = validate(rec, mode);
      if (!v.ok) throw new Error(`${rec.id}: ${v.errors[0]}`);
      console.log(`${rec.id}: s = ${sc.toFixed(6)}, ${validate(rec, "nofold").ok ? "inside faces" : "crosses edges"} (${Date.now() - t} ms)`);
      packings.push(rec);
    }
  }
}
writeFileSync(
  new URL("../../../python/surface/fixtures/johnson_packings.json", import.meta.url),
  JSON.stringify({ note: "Test packings only (not records), generated by packages/surface/scripts/build-johnson-packings.ts.", packings }, null, 1) + "\n",
);
console.log(`wrote ${packings.length} test packings`);
