/**
 * Test packings (not records) for the generalised surfaces and the full range of N: short seeded searches on a
 * Catalan solid with kite faces (deltoidal icositetrahedron), one with rhombic faces (rhombic
 * dodecahedron), a prism (pentagonal) and an antiprism (square), with disks, triangles and hexagons,
 * with folding (P = 3, so that pieces cross edges) and without (P = F + 2, so that faces hold several
 * pieces), plus three folding packings on the sharpest Catalan vertex (triakis tetrahedron), the
 * chiral pentagonal icositetrahedron and a 9-gon antiprism; and N = 3, 7, 12, 20 and 100 on a cube, a
 * rhombic dodecahedron, a heptagonal prism and a pentagonal antiprism, with and without folding (P = 2
 * and 3). Each is float-checked here; the Python certifier's tests (python/surface/test_general.py)
 * certify every one, and the TypeScript tests validate them.
 *
 * Usage: npx tsx packages/surface/scripts/build-test-packings.ts python/surface/fixtures/general_packings.json
 */
import { writeFileSync } from "node:fs";
import { type SolidName, getSolid, validate } from "../src/index";
import { searchProblem } from "../src/search/search";

const out = process.argv[2];
if (!out) throw new Error("usage: build-test-packings.ts <out.json>");
const cases: { solid: SolidName; N: number; P: number; mode: "fold" | "nofold" }[] = [];
for (const solid of ["deltoidal_icositetrahedron", "rhombic_dodecahedron", "prism5", "antiprism4"] as SolidName[])
  for (const N of [0, 3, 6])
    for (const mode of ["fold", "nofold"] as const) cases.push({ solid, N, P: mode === "fold" ? 3 : getSolid(solid).F + 2, mode });
cases.push({ solid: "triakis_tetrahedron", N: 0, P: 4, mode: "fold" });
cases.push({ solid: "pentagonal_icositetrahedron", N: 4, P: 2, mode: "fold" });
cases.push({ solid: "antiprism9", N: 5, P: 3, mode: "fold" });
// the range of N of 2D in 2D (0 and 3 to 100): a spread on a Platonic solid, a Catalan solid, a prism
// and an antiprism
for (const solid of ["cube", "rhombic_dodecahedron", "prism7", "antiprism5"] as SolidName[])
  for (const N of [3, 7, 12, 20, 100])
    for (const mode of ["fold", "nofold"] as const) cases.push({ solid, N, P: mode === "fold" ? 2 : 3, mode });

const SEARCH = { seed: 1, randomStarts: 2, hops: 2 };
const records = [];
for (const c of cases) {
  const t = Date.now();
  // many-sided pieces get one start and one hop (a 100-gon's compression takes seconds)
  const search = c.N > 8 ? { seed: 1, randomStarts: 1, hops: 1 } : SEARCH;
  const r = searchProblem(getSolid(c.solid), c.N, c.P, { ...search, warm: [], mode: c.mode });
  if (!r) throw new Error(`no packing for ${c.solid} ${c.N} ${c.P} ${c.mode}`);
  const s = 1 / r.lam;
  const pieces = r.poses.map((p) => ({ face: p.face, x: p.x * s, y: p.y * s, theta: p.theta }));
  const cfg = { solid: c.solid, N: c.N, s, pieces };
  const v = validate(cfg, c.mode);
  if (!v.ok) throw new Error(`${c.solid} ${c.N} ${c.P} ${c.mode}: ${v.errors[0]}`);
  // a folding test packing must use folding: some piece leaves its face
  const crosses = !validate(cfg, "nofold").ok;
  if (c.mode === "fold" && !crosses) throw new Error(`${c.solid} ${c.N} ${c.P}: no piece crosses an edge`);
  const shared = new Set(pieces.map((p) => p.face)).size < pieces.length;
  console.log(`${c.solid} N=${c.N} P=${c.P} ${c.mode}: s = ${s.toFixed(6)}, ${crosses ? "crosses edges" : "inside faces"}${shared ? ", faces shared" : ""} (${Date.now() - t} ms)`);
  records.push({ id: `surface/${c.solid}/${c.mode}/${c.N}/${c.P}`, solid: c.solid, mode: c.mode, N: c.N, P: c.P, s, pieces, search });
}
writeFileSync(
  out,
  JSON.stringify({ note: "test packings (not records), generated by packages/surface/scripts/build-test-packings.ts", records }) + "\n",
);
console.log("wrote", records.length, "test packings to", out);
