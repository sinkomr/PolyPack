/**
 * Construct small test packings on mixed regular faces, without search or optimisation.
 * Fold cases cross a mixed-face edge; nofold cases use every face kind and share one face.
 * Usage: node --import tsx packages/surface/scripts/build-archimedean-packings.ts
 */
import { writeFileSync } from "node:fs";
import { boundingRadius } from "@polypack/geometry";
import { apply, faceVertex, getSolid, glue, inverse, validate, type SolidName, type SurfacePose } from "../src/index";

const packings = [];
for (const solid of ["truncated_tetrahedron", "cuboctahedron", "snub_cube", "truncated_icosidodecahedron"] as SolidName[]) {
  const S = getSolid(solid);
  const kinds = [...new Set(S.sides)].sort((a, b) => a - b);
  for (const N of [0, 3, 12]) {
    const R = boundingRadius(N);
    const s = 16 * R;
    for (const mode of ["fold", "nofold"] as const) {
      let pieces: SurfacePose[];
      if (mode === "nofold") {
        pieces = kinds.map((m) => ({ face: S.sides.indexOf(m), x: 0, y: 0, theta: 0.173 }));
        // Two separated pieces on a face of the smallest kind, still well inside its walls.
        pieces[0].x = -1.2 * R;
        pieces.push({ ...pieces[0], x: 1.2 * R, theta: 0.317 });
      } else {
        const f = S.faces.findIndex((_, fi) => S.sides[fi] === kinds[0] && S.adj[fi].some((g) => S.sides[g.face] !== S.sides[fi]));
        const k = S.adj[f].findIndex((g) => S.sides[g.face] !== S.sides[f]);
        if (k < 0) throw new Error(`${solid}: no mixed-face edge`);
        const a = faceVertex(S, s, f, k);
        const b = faceVertex(S, s, f, k + 1);
        const dx = b[0] - a[0], dy = b[1] - a[1];
        const L = Math.hypot(dx, dy);
        const nx = -dy / L, ny = dx / L;
        const d = 0.15 * R;
        const g = glue(S, s, f, k);
        const p = { face: f, x: a[0] + 0.31 * dx + d * nx, y: a[1] + 0.31 * dy + d * ny, theta: 0.173 };
        const q = apply(inverse(g.T), a[0] + 0.69 * dx - d * nx, a[1] + 0.69 * dy - d * ny);
        pieces = [p, { face: g.face, x: q[0], y: q[1], theta: 0.317 }];
      }
      const packing = { id: `surface/${solid}/${mode}/${N}/${pieces.length}`, solid, mode, N, P: pieces.length, s, pieces };
      const v = validate(packing, mode, { tol: 0 });
      if (!v.ok) throw new Error(`${packing.id}: ${v.errors.join(", ")}`);
      if (mode === "fold" && validate(packing, "nofold").ok) throw new Error(`${packing.id}: no crossing`);
      packings.push(packing);
    }
  }
}
writeFileSync(new URL("../../../python/surface/fixtures/archimedean_packings.json", import.meta.url), JSON.stringify({
  note: "Constructed test packings only, without search; generated by packages/surface/scripts/build-archimedean-packings.ts.",
  packings,
}, null, 2) + "\n");
console.log(`wrote ${packings.length} test packings`);
