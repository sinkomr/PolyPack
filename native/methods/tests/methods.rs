//! The generic methods on a toy kernel (P unit balls on a line in a segment of length s, which
//! minimises s: the answer is P), and the generic parts alone: the random stream, L-BFGS, the
//! framework's budget, stop and bound. The ndim kernel, the real user, is tested bit for bit
//! against the TypeScript in native/ndim/tests/search.rs.

use polypack_methods::basin::run_basin_hopping;
use polypack_methods::framework::{run_method, RunOptions, Stopped};
use polypack_methods::kernel::{FamilyKernel, Finished, KernelState, Throw, Validation};
use polypack_methods::lbfgs::{lbfgs, LbfgsOptions};
use polypack_methods::random::{random_int, sample, Mulberry32};

#[test]
fn mulberry32_is_the_typescripts() {
    // generated by the TypeScript mulberry32 (packages/methods/src/random.ts)
    let want: [(u32, [f64; 5]); 3] = [
        (0, [0.26642920868471265, 0.0003297457005828619, 0.2232720274478197, 0.1462021479383111, 0.46732782293111086]),
        (42, [0.6011037519201636, 0.44829055899754167, 0.8524657934904099, 0.6697340414393693, 0.17481389874592423]),
        (4294967295, [0.8964226141106337, 0.189478256739676, 0.7156526781618595, 0.9440599093213677, 0.8452364315744489]),
    ];
    for (seed, vals) in want {
        let mut r = Mulberry32::new(seed);
        for v in vals {
            assert_eq!(r.next(), v, "seed {seed}");
        }
    }
}

#[test]
fn integers_and_samples() {
    let mut r = Mulberry32::new(5);
    for n in [1usize, 2, 7, 1000] {
        for _ in 0..200 {
            assert!(random_int(&mut r, n) < n);
        }
    }
    let s = sample(&mut r, 10, 4);
    assert_eq!(s.len(), 4);
    let mut sorted = s.clone();
    sorted.sort();
    sorted.dedup();
    assert_eq!(sorted.len(), 4);
    assert!(s.iter().all(|&i| i < 10));
    // the whole range is a permutation
    let mut all = sample(&mut r, 6, 6);
    all.sort();
    assert_eq!(all, vec![0, 1, 2, 3, 4, 5]);
}

#[test]
fn lbfgs_minimises_a_quadratic_and_stops_with_the_caller() {
    // f = sum (i + 1) (x_i - i)^2
    let n = 6;
    let mut f = |x: &[f64], g: &mut [f64]| -> Result<f64, Throw> {
        let mut e = 0.0;
        for i in 0..n {
            let c = (i + 1) as f64;
            e += c * (x[i] - i as f64) * (x[i] - i as f64);
            g[i] = 2.0 * c * (x[i] - i as f64);
        }
        Ok(e)
    };
    let (x, fx) = lbfgs(&mut f, &vec![5.0; n], &LbfgsOptions { max_iter: 200, target: 1e-20, max_step: 0.5 }).unwrap();
    assert!(fx < 1e-12, "{fx}");
    for (i, v) in x.iter().enumerate() {
        assert!((v - i as f64).abs() < 1e-6);
    }
    // an error of the function ends the run at once
    let mut calls = 0;
    let mut bad = |_: &[f64], g: &mut [f64]| -> Result<f64, Throw> {
        calls += 1;
        g.fill(1.0);
        if calls > 3 {
            Err(Throw::Error("stop".into()))
        } else {
            Ok(10.0)
        }
    };
    assert_eq!(lbfgs(&mut bad, &[0.0; 3], &LbfgsOptions { max_iter: 50, target: 0.0, max_step: 1.0 }).unwrap_err(), Throw::Error("stop".into()));
    // a start already below the target, and no variables, return at once
    let mut zero = |_: &[f64], g: &mut [f64]| -> Result<f64, Throw> {
        g.fill(0.0);
        Ok(0.0)
    };
    assert_eq!(lbfgs(&mut zero, &[1.0], &LbfgsOptions { max_iter: 9, target: 1.0, max_step: 1.0 }).unwrap().1, 0.0);
}

/// P unit balls on a line, in the segment [-s/2, s/2]; the state is the centres, the size s.
struct Line {
    p: usize,
    steps: Vec<f64>,
}

impl Line {
    fn new(p: usize) -> Line {
        Line { p, steps: vec![0.5] }
    }
    fn valid(c: &[f64], tol: f64) -> bool {
        let s = c[0];
        let xs = &c[1..];
        xs.iter().all(|x| x.abs() + 0.5 <= s / 2.0 + tol)
            && (0..xs.len()).all(|i| (i + 1..xs.len()).all(|j| (xs[i] - xs[j]).abs() >= 1.0 - tol))
    }
    fn terms(&self, s: &KernelState<()>, only: Option<usize>, mut grad: Option<&mut [f64]>) -> f64 {
        let mut e = 0.0;
        let mut gs = 0.0;
        let mut wall = |i: usize, e: &mut f64, grad: &mut Option<&mut [f64]>| {
            let viol = s.x[i].abs() + 0.5 - s.size / 2.0;
            if viol > 0.0 {
                *e += viol * viol;
                if let Some(g) = grad.as_deref_mut() {
                    g[i] += 2.0 * viol * s.x[i].signum();
                    gs -= viol;
                }
            }
        };
        let pair = |i: usize, j: usize, e: &mut f64, grad: &mut Option<&mut [f64]>| {
            let o = 1.0 - (s.x[j] - s.x[i]).abs();
            if o > 0.0 {
                *e += o * o;
                if let Some(g) = grad.as_deref_mut() {
                    let sg = (s.x[j] - s.x[i]).signum();
                    g[i] += 2.0 * o * sg;
                    g[j] -= 2.0 * o * sg;
                }
            }
        };
        match only {
            Some(k) => {
                wall(k, &mut e, &mut grad);
                for j in 0..self.p {
                    if j != k {
                        pair(k.min(j), k.max(j), &mut e, &mut grad);
                    }
                }
            }
            None => {
                for i in 0..self.p {
                    wall(i, &mut e, &mut grad);
                    for j in i + 1..self.p {
                        pair(i, j, &mut e, &mut grad);
                    }
                }
            }
        }
        if let Some(g) = grad {
            g[self.p] = gs;
        }
        e
    }
}

impl FamilyKernel for Line {
    type Aux = ();
    type Config = Vec<f64>;
    fn p(&self) -> usize {
        self.p
    }
    fn dim(&self) -> usize {
        1
    }
    fn steps(&self) -> &[f64] {
        &self.steps
    }
    fn globals(&self) -> usize {
        0
    }
    fn global_steps(&self) -> &[f64] {
        &[]
    }
    fn bound(&self) -> Option<f64> {
        Some(self.p as f64 * (1.0 - 1e-12))
    }
    fn finish_cost(&self) -> f64 {
        20.0
    }
    fn validate_cost(&self) -> Option<f64> {
        Some(3.0)
    }
    fn grad_cost(&self) -> Option<f64> {
        None
    }
    fn has_swap(&self) -> bool {
        false
    }
    fn has_seeds(&self) -> bool {
        true
    }
    fn from_config(&mut self, c: &Vec<f64>) -> Option<KernelState<()>> {
        (c.len() == self.p + 1 && c.iter().all(|v| v.is_finite()) && c[0] > 0.0)
            .then(|| KernelState { x: c[1..].to_vec(), size: c[0], aux: () })
    }
    fn to_config(&mut self, s: &KernelState<()>) -> Result<Vec<f64>, Throw> {
        let mut c = vec![s.size];
        c.extend(&s.x);
        Ok(c)
    }
    fn same_config(&self, a: &Vec<f64>, b: &Vec<f64>) -> bool {
        a == b
    }
    fn rebase(&mut self, _: &mut KernelState<()>) {}
    fn random_start(&mut self, rng: &mut Mulberry32) -> KernelState<()> {
        let size = 2.0 * self.p as f64;
        KernelState { x: (0..self.p).map(|_| (rng.next() - 0.5) * size).collect(), size, aux: () }
    }
    fn random_pose(&mut self, s: &mut KernelState<()>, i: usize, rng: &mut Mulberry32) {
        s.x[i] = (rng.next() - 0.5) * s.size;
    }
    fn jiggle(&mut self, s: &mut KernelState<()>, i: usize, amount: f64, rng: &mut Mulberry32) {
        s.x[i] += (2.0 * rng.next() - 1.0) * amount * 0.5;
    }
    fn set_size(&mut self, s: &mut KernelState<()>, size: f64) {
        let f = size / s.size;
        s.x.iter_mut().for_each(|x| *x *= f);
        s.size = size;
    }
    fn energy(&mut self, s: &KernelState<()>, grad: Option<&mut [f64]>, _: Option<&[f64]>) -> Result<f64, Throw> {
        let mut grad = grad;
        if let Some(g) = grad.as_deref_mut() {
            g.fill(0.0);
        }
        Ok(self.terms(s, None, grad))
    }
    fn piece_energy(&mut self, s: &KernelState<()>, i: usize, _: Option<&[f64]>) -> Result<f64, Throw> {
        Ok(self.terms(s, Some(i), None))
    }
    fn finish(&mut self, s: &KernelState<()>, _: &mut dyn FnMut() -> bool) -> Result<Option<Finished<Vec<f64>>>, Throw> {
        // the centres and the container scale together by the smallest factor f >= 1 that separates the pairs
        let mut gap = f64::INFINITY;
        for i in 0..self.p {
            for j in i + 1..self.p {
                gap = gap.min((s.x[i] - s.x[j]).abs());
            }
        }
        let f = if gap < 1.0 { 1.0 / gap * (1.0 + 1e-12) } else { 1.0 };
        let xs: Vec<f64> = s.x.iter().map(|x| x * f).collect();
        let size = xs.iter().fold(0.0f64, |m, x| m.max(2.0 * (x.abs() + 0.5)));
        let mut config = vec![size];
        config.extend(xs);
        Ok(Some(Finished { score: size, config }))
    }
    fn seeds(&mut self, _: &mut Mulberry32, _: usize) -> Vec<KernelState<()>> {
        let p = self.p as f64;
        vec![KernelState { x: (0..self.p).map(|i| (i as f64 - (p - 1.0) / 2.0) * 1.2).collect(), size: 1.3 * p, aux: () }]
    }
    fn swap(&mut self, _: &mut KernelState<()>, _: usize, _: usize) {}
}

fn run(p: usize, seed: u32, evals: Option<f64>, start: Option<Vec<f64>>, stop_after: Option<f64>) -> polypack_methods::framework::RunResult<Vec<f64>> {
    let mut k = Line::new(p);
    let mut stop = |used: f64, _: bool| stop_after.is_some_and(|a| used >= a);
    let mut validate = |c: &Vec<f64>| Validation { valid: Line::valid(c, 1e-9), score: Some(c[0]) };
    run_method(&mut k, RunOptions { seed, start, evals, should_stop: &mut stop, validate: &mut validate }, run_basin_hopping).unwrap()
}

#[test]
fn basin_hopping_packs_a_line() {
    for p in [2usize, 3, 5] {
        let r = run(p, 3, Some(4000.0), None, None);
        let c = r.config.expect("a result");
        assert!(Line::valid(&c, 1e-9));
        assert!(c[0] >= p as f64 * (1.0 - 1e-9) && c[0] < p as f64 + 1e-3, "P = {p}: {}", c[0]);
        assert_eq!(r.score, Some(c[0]));
        // the run ends at its budget, or at the bound when it reaches the optimum
        assert!(matches!(r.stopped, Stopped::Evals | Stopped::Bound), "{:?}", r.stopped);
        assert!(r.evaluations <= 4001.0 + 1.0);
        // the same seed, the same run
        let again = run(p, 3, Some(4000.0), None, None);
        assert_eq!((again.evaluations, again.config), (r.evaluations, Some(c)));
    }
}

#[test]
fn a_start_is_never_made_worse_and_the_stop_ends_the_run() {
    let start = vec![8.0, -3.0, -1.0, 1.0, 3.0];
    let a = run(4, 1, Some(300.0), Some(start.clone()), None);
    assert!(a.score.unwrap() <= 8.0);
    // a stop that comes at 100 evaluations: the best so far, never worse than the start
    let b = run(4, 1, None, Some(start), Some(100.0));
    assert_eq!(b.stopped, Stopped::Stopped);
    assert!(b.score.unwrap() <= 8.0);
    assert!(b.evaluations >= 100.0 && b.evaluations < 400.0, "{}", b.evaluations);
    // a stop at once: no result
    let c = run(4, 1, None, None, Some(0.0));
    assert_eq!(c.stopped, Stopped::Stopped);
    assert!(c.config.is_none() && c.evaluations == 0.0);
    assert_eq!(c.reasons, vec!["no valid configuration found".to_string()]);
}

#[test]
fn a_budget_that_is_not_positive_is_refused() {
    let mut k = Line::new(2);
    let mut stop = |_: f64, _: bool| false;
    let mut validate = |c: &Vec<f64>| Validation { valid: Line::valid(c, 1e-9), score: Some(c[0]) };
    for evals in [0.0, -1.0, f64::NAN] {
        let e = run_method(&mut k, RunOptions { seed: 1, start: None, evals: Some(evals), should_stop: &mut stop, validate: &mut validate }, run_basin_hopping);
        assert_eq!(e.err().as_deref(), Some("the budget must be positive"));
    }
}
