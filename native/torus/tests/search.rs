//! The search against the TypeScript's `searchTorus` (fixtures/search-ref.jsonl, written by Node
//! running packages/torus/src/search.ts on Linux x86-64) and unit tests of its parts.
//! With an evaluation-only budget the port must give the same packing bit for bit.

use polypack_torus::search::{
    family_lattice, scale_search, search_torus, Mulberry32, Stop, TorusProblem, TorusSearchOptions, Stopped,
};
use polypack_torus::{validation_steps, Lattice, Pose, TorusFamily, TorusPacking, ValidateOptions};
use serde_json::Value;

fn num(v: &Value) -> f64 {
    v.as_f64().unwrap()
}

fn packing_of(family: TorusFamily, n: usize, v: &Value) -> TorusPacking {
    let vec2 = |a: &Value| [num(&a[0]), num(&a[1])];
    TorusPacking {
        family,
        n: n as f64,
        lattice: Lattice {
            b1: vec2(&v["lattice"]["b1"]),
            b2: vec2(&v["lattice"]["b2"]),
        },
        poses: v["poses"]
            .as_array()
            .unwrap()
            .iter()
            .map(|q| Pose {
                x: num(&q[0]),
                y: num(&q[1]),
                theta: num(&q[2]),
            })
            .collect(),
    }
}

#[test]
fn matches_the_typescript_search_bit_for_bit() {
    let path = format!("{}/tests/fixtures/search-ref.jsonl", env!("CARGO_MANIFEST_DIR"));
    let text = std::fs::read_to_string(path).unwrap();
    let mut count = 0;
    for line in text.lines().filter(|l| !l.trim().is_empty()) {
        let case: Value = serde_json::from_str(line).unwrap();
        let id = case["id"].as_str().unwrap();
        let parts: Vec<&str> = id.split('/').collect();
        let family = TorusFamily::parse(parts[1]).unwrap();
        let (n, p): (usize, usize) = (parts[2].parse().unwrap(), parts[3].parse().unwrap());
        let start = (!case["start"].is_null()).then(|| packing_of(family, n, &case["start"]));
        let mut o = TorusSearchOptions::new(case["seed"].as_u64().unwrap() as u32);
        o.max_evals = case["evals"].as_u64().unwrap();
        o.start = start.as_ref();
        let r = search_torus(&TorusProblem { family, n, p }, &o).unwrap();
        let want = &case["result"];
        assert_eq!(r.stopped, Stopped::Evals, "{id}");
        assert_eq!(r.evaluations, want["evaluations"].as_u64().unwrap(), "{id} evaluations");
        assert_eq!(r.hops, want["hops"].as_u64().unwrap(), "{id} hops");
        assert_eq!(r.score, num(&want["score"]), "{id}: score {} vs {}", r.score, want["score"]);
        match want["start_score"].as_f64() {
            Some(s) => assert_eq!(r.start_score, Some(s), "{id} start score"),
            None => assert_eq!(r.start_score, None, "{id} start score"),
        }
        let got = r.packing.expect("a packing");
        let exp = packing_of(family, n, &want["packing"]);
        assert_eq!(got.lattice, exp.lattice, "{id} lattice");
        assert_eq!(got.poses, exp.poses, "{id} poses");
        // and the packing is valid by the validator at 1e-9
        let v = validation_steps(&got, &ValidateOptions::default());
        assert!(v.valid && v.errors.is_empty(), "{id} valid");
        count += 1;
    }
    assert!(count >= 5, "{count} cases");
}

#[test]
fn mulberry32_is_the_typescripts() {
    // generated by the TypeScript mulberry32 (search.ts)
    let want: [(u32, [f64; 5]); 3] = [
        (0, [0.26642920868471265, 0.0003297457005828619, 0.2232720274478197, 0.1462021479383111, 0.46732782293111086]),
        (42, [0.6011037519201636, 0.44829055899754167, 0.8524657934904099, 0.6697340414393693, 0.17481389874592423]),
        (4294967295, [0.8964226141106337, 0.189478256739676, 0.7156526781618595, 0.9440599093213677, 0.8452364315744489]),
    ];
    for (seed, vals) in want {
        let mut r = Mulberry32::new(seed);
        for v in vals {
            assert_eq!(r.next(), v, "seed {seed}");
        }
    }
}

#[test]
fn family_lattices() {
    let sq = family_lattice(TorusFamily::Sq, 2.0);
    assert_eq!((sq.b1, sq.b2), ([2.0, 0.0], [0.0, 2.0]));
    let hex = family_lattice(TorusFamily::Hex, 2.0);
    assert_eq!(hex.b1, [2.0, 0.0]);
    assert_eq!(hex.b2[0], 1.0);
    assert!((hex.b2[1] - 3f64.sqrt()).abs() < 1e-15);
}

#[test]
fn scale_search_finds_the_threshold_from_both_sides() {
    for threshold in [0.7, 1.0, 1.0005, 1.3, 5.0] {
        let mut calls = 0;
        let k = scale_search(&mut |k| {
            calls += 1;
            Ok(k >= threshold)
        })
        .unwrap()
        .unwrap();
        assert!(k >= threshold && k - threshold <= 1e-13 * k, "{threshold}: {k}");
        assert!(calls < 200);
    }
    // no valid k within a factor of about 14
    assert_eq!(scale_search(&mut |k| Ok(k >= 100.0)).unwrap(), None);
    // a stop from the test propagates
    assert_eq!(scale_search(&mut |_| Err(Stop::Aborted)), Err(Stop::Aborted));
}

#[test]
fn bad_problems_and_stops() {
    let o = TorusSearchOptions::new(1);
    let bad = |n, p| search_torus(&TorusProblem { family: TorusFamily::Sq, n, p }, &o);
    assert_eq!(bad(2, 3).unwrap_err(), "bad torus problem");
    assert_eq!(bad(101, 3).unwrap_err(), "bad torus problem");
    assert_eq!(bad(4, 0).unwrap_err(), "bad torus problem");
    // a stop at once: no packing, aborted, one evaluation counted
    let stop = || true;
    let mut o = TorusSearchOptions::new(1);
    o.should_stop = Some(&stop);
    let r = search_torus(&TorusProblem { family: TorusFamily::Sq, n: 4, p: 3 }, &o).unwrap();
    assert_eq!((r.stopped, r.packing.is_none(), r.evaluations), (Stopped::Aborted, true, 1));
    // a budget of 0 evaluations
    let mut o = TorusSearchOptions::new(1);
    o.max_evals = 0;
    let r = search_torus(&TorusProblem { family: TorusFamily::Hex, n: 0, p: 3 }, &o).unwrap();
    assert_eq!((r.stopped, r.score, r.evaluations), (Stopped::Evals, f64::INFINITY, 0));
}
