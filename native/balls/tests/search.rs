//! The search against the TypeScript's `searchBalls` and `runSpaceJob` (fixtures/search-ref.jsonl, written by
//! native/tools/balls-search-ref.mts on Node 24 for Linux x86-64). With an evaluation-only budget the port must
//! give the same configuration, score, evaluation count and ending bit for bit. Also unit tests of the random
//! stream, the legalization and the L-BFGS.

use polypack_balls::auto::{auto_search, parse_id, METHOD};
use polypack_balls::ball_pieces::{legalize_balls, lattice_cut};
use polypack_balls::lbfgs::lbfgs;
use polypack_balls::random::{gauss, Rng};
use polypack_balls::search::{search_balls, BallsSearchOptions, Stopped};
use polypack_balls::{get_balls_problem, validate_balls, BallsConfig, BallsValidateOptions};
use polypack_spaceauto::AutoJob;
use serde_json::Value;
use std::sync::atomic::AtomicBool;
use std::time::{Duration, Instant};

fn config_of(v: &Value) -> BallsConfig {
    BallsConfig {
        s: v["s"].as_f64().unwrap(),
        pieces: v["pieces"]
            .as_array()
            .unwrap()
            .iter()
            .map(|p| p.as_array().unwrap().iter().map(|x| x.as_f64().unwrap()).collect())
            .collect(),
    }
}

fn load() -> Vec<Value> {
    let path = format!("{}/tests/fixtures/search-ref.jsonl", env!("CARGO_MANIFEST_DIR"));
    std::fs::read_to_string(path)
        .unwrap()
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).unwrap())
        .collect()
}

#[test]
fn matches_the_typescript_search_bit_for_bit() {
    let cases = load();
    let (mut searches, mut jobs) = (0, 0);
    for case in &cases {
        let name = case["name"].as_str().unwrap();
        let id = case["id"].as_str().unwrap();
        let seed = case["seed"].as_u64().unwrap() as u32;
        let evals = case["evals"].as_u64().unwrap();
        let start = (!case["start"].is_null()).then(|| config_of(&case["start"]));
        let want = &case["result"];
        let b = parse_id(id).unwrap();
        match case["kind"].as_str().unwrap() {
            "search" => {
                let mut o = BallsSearchOptions::new(seed);
                o.max_evals = evals;
                o.start = start.as_ref();
                let r = search_balls(b.problem, b.p, &o).unwrap();
                assert_eq!(r.stopped, Stopped::Evals, "{name}");
                assert_eq!(r.evaluations, want["evaluations"].as_u64().unwrap(), "{name} evaluations");
                assert_eq!(r.hops, want["hops"].as_u64().unwrap(), "{name} hops");
                assert_eq!(want["stopped"], "evals", "{name}");
                match want["start_score"].as_f64() {
                    Some(s) => assert_eq!(r.start_score, Some(s), "{name} start score"),
                    None => assert_eq!(r.start_score, None, "{name} start score"),
                }
                assert_eq!(r.config.as_ref().map(|c| c.s), want["score"].as_f64(), "{name} score");
                assert_eq!(r.config, Some(config_of(&want["config"])), "{name} configuration");
                searches += 1;
            }
            _ => {
                let stop = AtomicBool::new(false);
                let start_json = (!case["start"].is_null()).then(|| case["start"].clone());
                let job = AutoJob {
                    id,
                    start: start_json.as_ref(),
                    seed,
                    max_evals: Some(evals),
                    deadline: Instant::now() + Duration::from_secs(600),
                    stop: &stop,
                };
                let r = auto_search(&job).unwrap();
                assert_eq!(r.method, METHOD);
                assert_eq!(r.stopped, want["termination"].as_str().unwrap(), "{name} termination");
                assert_eq!(r.evaluations, want["evaluations"].as_u64().unwrap(), "{name} evaluations");
                assert_eq!(r.score, want["score"].as_f64(), "{name} score");
                assert_eq!(r.config.as_ref().map(config_of), (!want["config"].is_null()).then(|| config_of(&want["config"])), "{name} configuration");
                jobs += 1;
            }
        }
    }
    assert!(searches >= 20 && jobs >= 4, "{searches} searches, {jobs} jobs");
}

#[test]
fn mulberry32_and_gauss_are_the_typescripts() {
    // generated by random.ts mulberry32 (the first five numbers), and its gauss from the same stream
    let mut r = Rng::new(0);
    let first: Vec<f64> = (0..5).map(|_| r.next()).collect();
    assert_eq!(first[0], 0.26642920868471265);
    assert_eq!(first[1], 0.0003297457005828619);
    assert_eq!(first[2], 0.2232720274478197);
    // gauss uses two numbers of the stream and is finite
    let g = gauss(&mut r);
    assert!(g.is_finite());
}

#[test]
fn legalization_separates_coincident_centres() {
    let p = get_balls_problem("ballinball").unwrap();
    let c = legalize_balls(p, &[[0.0; 3], [0.0; 3], [0.1, 0.0, 0.0]], 1e-10, 1e-10).unwrap();
    let v = validate_balls(p, &c, &BallsValidateOptions { tol: Some(0.0), max_errors: None }).unwrap();
    assert!(v.valid, "{:?}", v.errors);
}

#[test]
fn lattice_cuts_have_p_points_of_every_container() {
    for code in ["ballinball", "ballincub", "ballinpkd", "ballinbp5"] {
        let p = get_balls_problem(code).unwrap();
        for kind in ["fcc", "hcp", "sc"] {
            let mut rng = Rng::new(7);
            let pts = lattice_cut(p, 17, &mut rng, kind, true).unwrap();
            assert_eq!(pts.len(), 17, "{code} {kind}");
        }
    }
}

#[test]
fn lbfgs_minimises_a_quadratic_and_stops_on_error() {
    let mut x = vec![3.0, -2.0, 5.0];
    let mut f = |x: &[f64], g: &mut [f64]| {
        let mut e = 0.0;
        for i in 0..3 {
            e += (i as f64 + 1.0) * x[i] * x[i];
            g[i] = 2.0 * (i as f64 + 1.0) * x[i];
        }
        Ok(e)
    };
    let fx = lbfgs(&mut f, &mut x, 100, 8, 1e-12).unwrap();
    assert!(fx < 1e-20 && x.iter().all(|v| v.abs() < 1e-9), "{fx} {x:?}");
    let mut n = 0;
    let mut stopper = |_x: &[f64], g: &mut [f64]| {
        n += 1;
        g.fill(1.0);
        if n > 3 {
            Err(polypack_balls::stop::Stop::new(polypack_balls::stop::Why::Aborted))
        } else {
            Ok(1.0)
        }
    };
    let mut y = vec![0.0, 0.0];
    assert!(lbfgs(&mut stopper, &mut y, 100, 8, 1e-12).is_err());
}
